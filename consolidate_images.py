#!/usr/bin/env python3
"""Consolidate qualreas images into data/images and update the references.

Run from the top of the qualreas clone:

    python3 consolidate_images.py            # dry run: shows what it would do
    python3 consolidate_images.py --write    # does it (uses git mv / git rm)
    python3 consolidate_images.py --write --drop-ontology-images
                                             # also removes the 4 unreferenced
                                             # diagrams already in data/images

What it does
  1. git rm: unused images (old output_*.png, docs/time_point_algebras_files/,
     duplicates in notebooks/Images/, Figure_5_Allen_1983.jpg).
  2. git mv: the images the notebooks use (docs/_static, notebooks/Images,
     notebooks/IMG_2285.jpeg) into data/images/.
  3. Rewrites references, as plain text so the JSON formatting of the notebooks
     is untouched:
        ../docs/_static/NAME   -> ../data/images/NAME      (notebooks, docs/*.rst)
        Images/NAME            -> ../data/images/NAME      (notebooks, docs/*.rst)
                                  data/images/NAME         (README.md, at the top level)
        'IMG_2285.jpeg'        -> '../data/images/IMG_2285.jpeg'
  4. Checks that every image path mentioned in the notebooks now exists.

docs/output_N_0.png files are generated by nbconvert and referenced by the
rst files; they are left alone.
"""
import re
import subprocess
import sys
from pathlib import Path

WRITE = "--write" in sys.argv
DROP_ONTOLOGY = "--drop-ontology-images" in sys.argv
root = Path.cwd()
if not (root / "src" / "qualreas.py").exists():
    sys.exit("Run this from the top-level qualreas directory.")

DEST = "data/images"

REMOVE = (
    ["docs/output_271_0.png", "docs/output_321_0.png", "docs/output_37_0.png",
     "docs/output_42_0.png", "docs/output_47_0.png",
     "docs/time_point_algebras_files",
     "notebooks/Images/Figure_5_Allen_1983.jpg"]
    + [f"notebooks/Images/{n}" for n in (
        "Allens_Interval_Relations.png", "Extension_of_Allens_Interval_Relations.png",
        "Left_Branching_Time_Relations.png", "Point_Interval_Relations.png",
        "Right_Branching_Time_Relations.png", "global_structures_of_time.png",
        "left_linearity_in_right_branching_time.png")]
)
if DROP_ONTOLOGY:
    REMOVE += [f"data/images/{n}" for n in (
        "AllensAlgebraOfProperTimeIntervals.png", "AllensAlgebraOfProperTimeIntervals_500width.png",
        "CoreModelOfTemporalEntities.png", "ProperInterval.png")]

MOVE = (
    [f"docs/_static/{n}" for n in (
        "Allens_Interval_Relations.png", "Extension_of_Allens_Interval_Relations.png",
        "Left_Branching_Time_Relations.png", "Point_Interval_Relations.png",
        "Right_Branching_Time_Relations.png", "global_structures_of_time.png",
        "left_linearity_in_right_branching_time.png")]
    + [f"notebooks/Images/{n}" for n in (
        "640px-RCC8.jpg", "Edge_Notation_Meaning.png", "wikipedia_rcc8_example.png",
        "Figure_5_Allen_1983.png", "janhunen2019_example_fig_1.png")]
    + ["notebooks/IMG_2285.jpeg"]
)


def git(*args):
    subprocess.run(["git", *args], check=True)


# ---- 1 and 2: remove and move files
for p in REMOVE:
    if (root / p).exists():
        print(("git rm   " if WRITE else "would rm  ") + p)
        if WRITE:
            git("rm", "-r", "-q", p)
    else:
        print("  (not found, skipped):", p)

(root / DEST).mkdir(parents=True, exist_ok=True)
for p in MOVE:
    if (root / p).exists():
        print(("git mv   " if WRITE else "would mv  ") + f"{p} -> {DEST}/")
        if WRITE:
            git("mv", p, DEST + "/")
    else:
        print("  (not found, skipped):", p)

# ---- 3: rewrite references
names = sorted({Path(p).name for p in MOVE if "IMG_" not in p})
alt = "|".join(re.escape(n) for n in names)
ND = "(?<![\\w/.])"  # not already part of a longer path

def rules_for(up):
    """Rules for a file that is `up` directories below the top level, e.g. up=1 for notebooks/x.ipynb."""
    pre = "../" * up + DEST
    return [
        (re.compile(r"\.\./docs/_static/(" + alt + ")"), pre + r"/\1"),
        (re.compile(ND + r"Images/(" + alt + ")"), pre + r"/\1"),
        (re.compile(r"(filename=\\?['\"])IMG_2285\.jpeg"), r"\1" + pre + "/IMG_2285.jpeg"),
    ]


rules_top = [  # README.md sits at the top level
    (re.compile(ND + r"Images/(" + alt + ")"), DEST + r"/\1"),
]

targets = [(p, rules_for(len(p.relative_to(root).parts) - 1)) for p in sorted((root / "notebooks").rglob("*.ipynb"))]
targets += [(p, rules_for(1)) for p in sorted((root / "docs").glob("*.rst"))]
targets += [(root / "README.md", rules_top)]

changed = 0
for p, rules in targets:
    old = p.read_text(encoding="utf-8")
    new = old
    for rx, rep in rules:
        new = rx.sub(rep, new)
    if new != old:
        changed += 1
        n = sum(1 for a, b in zip(old.splitlines(), new.splitlines()) if a != b)
        print(f"{'changed' if WRITE else 'would change'}: {p.relative_to(root)}  ({n} lines)")
        if WRITE:
            p.write_text(new, encoding="utf-8")
print(f"\n{changed} file(s) {'updated' if WRITE else 'would be updated'}.")

# ---- 4: check that image paths in the notebooks resolve
if WRITE:
    print("\nChecking image paths in notebooks...")
    pat = re.compile(r"""(?:filename=|Image\()\s*\\?["']([^"'\\]+\.(?:png|jpe?g))""", re.I)
    bad = 0
    for p in sorted((root / "notebooks").rglob("*.ipynb")):
        for m in pat.finditer(p.read_text(encoding="utf-8")):
            if not (p.parent / m.group(1)).exists():
                bad += 1
                print(f"  MISSING in {p.relative_to(root)}: {m.group(1)}")
    print("All image paths resolve." if not bad else f"{bad} path(s) need attention (see above).")
    print("\nNext: review with 'git status' / 'git diff', then commit and push yourself.")
